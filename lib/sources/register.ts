export function registerByStatus(status: RegisterStatus): SourceRegisterRow[] {
  return SOURCE_REGISTER.filter((row) => row.status === status)
}

/** Partner logins attach to a feed, not to a venue that the feed already covers. */
const PARTNER_SOURCE_CATEGORIES = new Set([
  'Ticketing',
  'Promoter',
  'Council',
  'Council open data',
  'Curated official schedules',
])

export function partnerSourceChoices(): SourceRegisterRow[] {
  return SOURCE_REGISTER.filter((row) =>
    PARTNER_SOURCE_CATEGORIES.has(row.category) &&
    (row.status === 'integrated' || row.status === 'partial' || row.status === 'queued'),
  )
}
