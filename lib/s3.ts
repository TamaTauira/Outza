import { DeleteObjectCommand, GetObjectCommand, HeadObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3'
import { getSignedUrl } from '@aws-sdk/s3-request-presigner'
import { createS3Client, getBucketConfig } from '@/lib/aws-config'

function shouldServeInline(contentType: string): boolean {
  // image/svg+xml excluded — SVGs can execute embedded scripts (XSS risk)
  return (contentType.startsWith('image/') && contentType !== 'image/svg+xml')
    || contentType.startsWith('video/')
    || contentType.startsWith('audio/')
}

let client: S3Client | null = null
const s3 = () => (client ??= createS3Client())

export function storagePath(rel: string, isPublic = true): string {
  const { folderPrefix } = getBucketConfig()
  return `${folderPrefix}${isPublic ? 'public/' : ''}${rel}`
}

/** Server-side upload of generated bytes (no ContentDisposition, so images render inline). */
export async function putObject(cloud_storage_path: string, body: Buffer, contentType: string): Promise<string> {
  const { bucketName } = getBucketConfig()
  await s3().send(new PutObjectCommand({
    Bucket: bucketName, Key: cloud_storage_path, Body: body, ContentType: contentType,
    CacheControl: 'public, max-age=31536000, immutable',
  }))
  return cloud_storage_path
}

export async function objectExists(cloud_storage_path: string): Promise<boolean> {
  try {
    await s3().send(new HeadObjectCommand({ Bucket: getBucketConfig().bucketName, Key: cloud_storage_path }))
    return true
  } catch {
    return false
  }
}

export function publicUrl(cloud_storage_path: string): string {
  const { bucketName } = getBucketConfig()
  const region = process.env.AWS_REGION ?? 'us-west-2'
  return `https://${bucketName}.s3.${region}.amazonaws.com/${cloud_storage_path.split('/').map(encodeURIComponent).join('/')}`
}

export async function getFileUrl(cloud_storage_path: string, contentType: string, isPublic: boolean): Promise<string> {
  if (isPublic) return publicUrl(cloud_storage_path)
  const { bucketName } = getBucketConfig()
  return getSignedUrl(s3(), new GetObjectCommand({
    Bucket: bucketName, Key: cloud_storage_path,
    ResponseContentDisposition: shouldServeInline(contentType) ? 'inline' : 'attachment',
  }), { expiresIn: 3600 })
}

export async function deleteFile(cloud_storage_path: string): Promise<void> {
  await s3().send(new DeleteObjectCommand({ Bucket: getBucketConfig().bucketName, Key: cloud_storage_path }))
}
